const TAMANO_PREDETERMINADO = 4 * 1024 * 1024
const TAMANO_CONFIGURADO = Number(import.meta.env.VITE_GARANTIA_TAMANO_MAXIMO_BYTES)

export const TAMANO_MAXIMO_GARANTIA_BYTES = Number.isFinite(TAMANO_CONFIGURADO)
  && TAMANO_CONFIGURADO > 0
  ? TAMANO_CONFIGURADO
  : TAMANO_PREDETERMINADO

export const TAMANO_MAXIMO_GARANTIA_MB = TAMANO_MAXIMO_GARANTIA_BYTES / (1024 * 1024)
